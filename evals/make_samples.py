"""Write samples/questions.md: 5 questions and the drafts the system made for them, taken from
the eval database after a full eval run (so they are the real system's output).

    cd backend && uv run python ../evals/make_samples.py

The samples: a typed fact question, a spoken multi-part message with an advice part, an advice
refusal, a question the corpus can't answer, and a question answered from the approved
canonical fee explainer.
"""

import json
import os
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).parent))
from harness import DEFAULT_DB, ROOT, Db  # noqa: E402

OUT = ROOT / "samples" / "questions.md"

SAMPLES = [
    ("A typed fact question", "text", "What is the exit load of HDFC Liquid Fund?"),
    ("A spoken multi-part message with an advice part", "voice",
     "What is the exit load of HDFC Liquid Fund, and should I redeem now?"),
    ("An advice question, refused", "text", "Should I invest in HDFC Mid Cap Fund now?"),
    ("A question the corpus can't answer", "text",
     "Who is the fund manager of HDFC Balanced Advantage Fund?"),
    ("Answered from the approved canonical fee explainer", "text",
     "Why is my regular plan charging more than the direct plan?"),
]  # fmt: skip


def message(db: Db, channel: str, text: str) -> dict[str, Any] | None:
    """The latest message on this channel with this text, ignoring case and punctuation. A
    spoken message is matched on its transcript, which may differ in punctuation only."""
    rows = db.fetch(
        "SELECT id, text_redacted, channel, split_method FROM message WHERE channel = $1 "
        "AND lower(regexp_replace(text_redacted, '[^a-zA-Z0-9 ]', '', 'g')) = "
        "lower(regexp_replace($2, '[^a-zA-Z0-9 ]', '', 'g')) ORDER BY created_at DESC LIMIT 1",
        channel,
        text,
    )
    return rows[0] if rows else None


def as_json(value: Any) -> Any:
    return json.loads(value) if isinstance(value, str) else value


def part_block(db: Db, item: dict[str, Any], n: int | None) -> list[str]:
    draft = db.fetch(
        "SELECT reply_redacted, source_type, routing, review_status, id FROM draft_version "
        "WHERE item_id = $1 ORDER BY version DESC LIMIT 1",
        item["id"],
    )[0]
    review = db.fetch("SELECT rule_results FROM review_result WHERE draft_version_id = $1",
                      draft["id"])  # fmt: skip
    rules = as_json(review[0]["rule_results"]) if review else []
    runs = db.fetch(
        "SELECT agent, status, output_json FROM agent_run WHERE item_id = $1 ORDER BY started_at",
        item["id"],
    )
    slots = as_json(item["shared_slots"]) or {}
    routing = as_json(draft["routing"]) or {}
    agents = []
    for r in runs:
        out = as_json(r["output_json"]) or {}
        if r["agent"] == "facts":
            agents.append(f"Facts: {out.get('status', r['status'])}")
        elif r["agent"] == "pattern":
            agents.append(f"Pattern: {out.get('label', r['status'])}")
        elif r["agent"] == "compliance":
            flags = [f"{f['type']} ({f['detail']})" for f in out.get("incoming_flags", [])]
            agents.append(f"Compliance: {', '.join(flags) or 'no flags'}")
    title = f"**Part {n}:** " if n else ""
    scheme = slots.get("scheme")
    inherited = " (carried over from another part)" if slots.get("scheme_inherited") else ""
    lines = [f"{title}{item['text_redacted']}", ""] if n else []
    lines += [
        f"- Intent: `{item['intent']}`" + (f", scheme `{scheme}`{inherited}" if scheme else ""),
        f"- Draft type: `{draft['source_type']}`, reviewer: {draft['review_status']} "
        f"({sum(1 for x in rules if x['passed'])} of {len(rules)} rules passed)",
        f"- Agents: {'; '.join(agents) or 'none'}",
        f"- Routing: {routing.get('team')}, {routing.get('priority')}, {routing.get('action')} "
        f"({routing.get('reason')})",
        "",
        "```",
        draft["reply_redacted"],
        "```",
        "",
    ]
    return lines


def main() -> None:
    db = Db(os.environ.get("EVAL_DATABASE_URL", DEFAULT_DB))
    out = [
        "# Sample questions and drafts",
        "",
        "Five questions as they went through the response loop in the final eval run, with",
        "the draft the desk produced for each. Generated by `evals/make_samples.py` from the",
        "eval database; nothing is edited by hand. Each draft still needs a person's approval",
        "before anything is written to the Google Doc or Gmail.",
        "",
        "The Pattern Agent's counts (\"Rising: 19 similar items this week\") come from the eval",
        "run itself, which asks many similar questions within a few minutes.",
        "",
    ]
    for i, (title, channel, text) in enumerate(SAMPLES, start=1):
        msg = message(db, channel, text)
        if msg is None:
            raise SystemExit(f"no {channel} message found for {text!r}: run the evals first")
        items = db.fetch(
            "SELECT id, text_redacted, intent, shared_slots FROM queue_item WHERE message_id = $1"
            " ORDER BY part_index",
            msg["id"],
        )
        heard = "Spoken; the confirmed transcript" if channel == "voice" else "Typed"
        out += [f"## {i}. {title}", "", f"{heard}: *{msg['text_redacted']}*", ""]
        if len(items) > 1:
            out += [f"Split into {len(items)} parts ({msg['split_method']} split).", ""]
        for n, item in enumerate(items, start=1):
            out += part_block(db, item, n if len(items) > 1 else None)
    OUT.write_text("\n".join(out).rstrip() + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
